-- The orm-probe's own three-table slice of the guide's PostgreSQL: the
-- posts/tags shape topics 16 and 17 teach, prefixed ormprobe_ so the probe
-- owns its tables outright. This file is the single schema source: sqlc
-- type-checks queries/posts.sql against it, the probe executes it verbatim
-- (embedded, CREATE TABLE IF NOT EXISTS, idempotent) to build the tables on
-- the guide's own PostgreSQL, and the GORM models map the same tables by
-- TableName() — one schema, three APIs, apples-to-apples.
CREATE TABLE IF NOT EXISTS ormprobe_posts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    body text NOT NULL,
    created_at timestamp with time zone NOT NULL
);

CREATE TABLE IF NOT EXISTS ormprobe_tags (
    name text PRIMARY KEY
);

CREATE TABLE IF NOT EXISTS ormprobe_post_tags (
    post_id bigint NOT NULL REFERENCES ormprobe_posts(id) ON DELETE CASCADE,
    tag_name text NOT NULL REFERENCES ormprobe_tags(name) ON DELETE CASCADE,
    PRIMARY KEY (post_id, tag_name)
);
