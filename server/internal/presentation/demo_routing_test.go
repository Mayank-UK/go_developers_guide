// The routing topic's demo endpoint, exercised through the same middleware
// chain production runs behind (the family rule that every new demo
// endpoint ships with a Go test).
//
// The wiring here is also the repo's one real http.StripPrefix mount: the
// routing topic teaches sub-router mounting, so this test builds the
// demo-area router with LOCAL patterns ("/explorer") and mounts it under
// the area prefix exactly as the mounting section describes — the outer
// subtree pattern is method-less so every method flows through, and the
// area mux's own method-aware patterns still produce the truthful 405s the
// envelope preserves. Production wires the flat route
// ("GET /api/demo/routing/explorer") in main.go; the mount is this
// package's exhibit for it.

// newRoutingDemoServer builds the demo area router, mounts it behind the
// production middleware chain, and returns the composed handler.
func newRoutingDemoServer() http.Handler {
	area := http.NewServeMux()
	area.Handle("GET /explorer", NewRoutingExplorerHandler())

	mux := http.NewServeMux()
	mux.Handle("/api/demo/routing/", http.StripPrefix("/api/demo/routing", area))

	var buf strings.Builder
	logger := newTestLogger(&buf)
	return Chain(
		RequestID,
		RequestLogger(logger),
		Recover(logger),
		EnvelopeMuxErrors(logger),
	)(mux)
}

func TestRoutingExplorerDemoServesThePayload(t *testing.T) {
	server := newRoutingDemoServer()

	rec := doRequest(server, http.MethodGet, "/api/demo/routing/explorer", "")
	if rec.Code != http.StatusOK {
		t.Fatalf("status = %d, want 200", rec.Code)
	}
	if ct := rec.Header().Get("Content-Type"); ct != "application/json" {
		t.Errorf("content type = %q, want application/json", ct)
	}
	if rec.Header().Get(core.RequestIDHeader) == "" {
		t.Error("every response must carry x-request-id")
	}

	// Spot-check the beats the topic's prose promises; the payload
	// builder's own tests pin the deep shape and the matcher's agreement
	// with the real ServeMux.
	decoded := struct {
		Routes []struct {
			Method  string `json:"method"`
			Pattern string `json:"pattern"`
			Kind    string `json:"kind"`
			Handler string `json:"handler"`
		} `json:"routes"`
		Probes []struct {
			Path    string   `json:"path"`
			Outcome string   `json:"outcome"`
			Status  int      `json:"status"`
			Allow   []string `json:"allow"`
		} `json:"probes"`
		Exhibits []struct {
			ID string `json:"id"`
		} `json:"exhibits"`
		Semantics struct {
			GetAlsoServesHead     bool `json:"getAlsoServesHead"`
			SubtreeRedirectStatus int  `json:"subtreeRedirectStatus"`
		} `json:"semantics"`
	}{}
	if err := json.Unmarshal(rec.Body.Bytes(), &decoded); err != nil {
		t.Fatalf("body not the demo DTO shape: %v\n%s", err, rec.Body.String())
	}
	if len(decoded.Routes) != 12 || decoded.Routes[2].Pattern != "/api/content/{topicId}" ||
		decoded.Routes[2].Kind != "wildcard" {
		t.Errorf("carried table drifted: %+v", decoded.Routes)
	}
	if len(decoded.Probes) != 9 {
		t.Errorf("probe count = %d, want 9", len(decoded.Probes))
	}
	if p := decoded.Probes[5]; p.Outcome != "method_not_allowed" || p.Status != 405 ||
		strings.Join(p.Allow, ",") != "GET,HEAD,PATCH" {
		t.Errorf("scenario 405 probe drifted: %+v", p)
	}
	if len(decoded.Exhibits) != 2 || decoded.Exhibits[0].ID != "precedence" {
		t.Errorf("exhibits drifted: %+v", decoded.Exhibits)
	}
	if !decoded.Semantics.GetAlsoServesHead || decoded.Semantics.SubtreeRedirectStatus != 307 {
		t.Errorf("semantics drifted: %+v", decoded.Semantics)
	}
}

func TestRoutingExplorerDemoEndpointRejectsNonGet(t *testing.T) {
	server := newRoutingDemoServer()

	rec := doRequest(server, http.MethodPost, "/api/demo/routing/explorer", "")
	if rec.Code != http.StatusMethodNotAllowed {
		t.Fatalf("status = %d, want 405", rec.Code)
	}
	// The 405 is generated by the AREA mux behind the mount — proof the
	// method-aware patterns survive StripPrefix — and the envelope keeps
	// its truthful status and Allow header.
	if !strings.Contains(rec.Body.String(), `"code":"not_found"`) {
		t.Errorf("405 body is not the envelope: %s", rec.Body.String())
	}
	if allow := rec.Header().Get("Allow"); !strings.Contains(allow, "GET") || !strings.Contains(allow, "HEAD") {
		t.Errorf("Allow header lost GET/HEAD through the mount: %q", allow)
	}
}

func TestRoutingDemoMountRedirectsItsSlashlessRoot(t *testing.T) {
	server := newRoutingDemoServer()

	// The mount pattern is a trailing-slash subtree: requesting the prefix
	// without the slash gets the method-preserving 307 to the slashed
	// form — the exact behavior the topic's subtree exhibit describes.
	rec := doRequest(server, http.MethodGet, "/api/demo/routing", "")
	if rec.Code != http.StatusTemporaryRedirect {
		t.Fatalf("status = %d, want 307", rec.Code)
	}
	if target := rec.Header().Get("Location"); target != "/api/demo/routing/" {
		t.Errorf("Location = %q, want /api/demo/routing/", target)
	}

	// And an unknown path under the mount is the mux's 404, rewritten into
	// the same error envelope by the chain.
	rec = doRequest(server, http.MethodGet, "/api/demo/routing/nope", "")
	if rec.Code != http.StatusNotFound {
		t.Fatalf("status = %d, want 404", rec.Code)
	}
	if !strings.Contains(rec.Body.String(), `"code":"not_found"`) {
		t.Errorf("404 body is not the envelope: %s", rec.Body.String())
	}
}
